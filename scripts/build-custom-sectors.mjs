import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Compacts data/custom-sectors/custom_sectors.json into the module the app reads.
// Run after regenerating the taxonomy: node scripts/build-custom-sectors.mjs
const root = process.cwd();
const { asOf, taxonomy } = JSON.parse(readFileSync(resolve(root, "data/custom-sectors/custom_sectors.json"), "utf8"));
const rows = taxonomy.flatMap(({ sector, subIndustries }) => subIndustries.map(({ name, codes }) =>
  `  [${JSON.stringify(sector)}, ${JSON.stringify(name)}, ${JSON.stringify(codes.join(" "))}],`));
writeFileSync(resolve(root, "shared/custom-sector-data.js"), `// Generated by scripts/build-custom-sectors.mjs from data/custom-sectors/custom_sectors.json; do not edit.
export const TAXONOMY_AS_OF = ${JSON.stringify(asOf)};
/** [sector, sub-industry, space-separated stock codes] */
export const SUB_INDUSTRIES = Object.freeze([
${rows.join("\n")}
]);
`);
console.log(`Wrote ${rows.length} sub-industries`);
