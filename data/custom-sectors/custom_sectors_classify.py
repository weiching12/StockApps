def main(path):
    rows = json.load(open(path, encoding="utf-8"))
    by_code = {r["公司代號"].strip(): r for r in rows}
    assigned = {}
    for sub, codes in OVERRIDES.items():
        assert sub in SUB_TO_SECTOR, f"unknown sub {sub}"
        for code in codes.split():
            assert code in by_code, f"{code} ({sub}) not in catalog"
            assert code not in assigned, f"{code} placed twice: {assigned.get(code)} / {sub}"
            assigned[code] = sub
    research = {}
    with open(RESEARCH, encoding="utf-8") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            assert row["code"] in by_code and row["sub"] in SUB_TO_SECTOR, row
            research[row["code"]] = row
    out = []
    for code, r in by_code.items():
        off_name, default_sub, broad = OFFICIAL[r["產業別"].strip()]
        sub = assigned.get(code, default_sub)
        review = (code not in assigned and broad) or code in LOW_CONFIDENCE
        basis = ""
        if code in research:
            sub, basis = research[code]["sub"], research[code]["basis"]
            review = "仍待確認" in basis
        out.append({"code": code, "name": r["公司簡稱"].strip(), "sector": SUB_TO_SECTOR[sub],
                    "subIndustry": sub, "twseIndustry": off_name, "needsReview": review, "basis": basis})
    order = {s: i for i, s in enumerate(SUB_TO_SECTOR)}
    out.sort(key=lambda x: (order[x["subIndustry"]], x["code"]))
    return out, rows[0]["出表日期"].strip()


